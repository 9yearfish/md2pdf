export { SUPPORTED_LANGUAGES, type LangSetting, type LangCode } from './lang';

export type PaperSize = 'a4' | 'us-letter' | 'a5' | 'iso-b5';

/** Page templates; what each one does is in src/layout/templates.ts. */
export type TemplateId = 'default' | 'report' | 'academic' | 'resume' | 'letter';
export const TEMPLATE_IDS: readonly TemplateId[] = ['default', 'report', 'academic', 'resume', 'letter'];

export interface DocumentOptions {
  paper: PaperSize;
  /** Page margin in millimetres. */
  margin: number;
  /** Body font size in points. */
  fontSize: number;
  /** Multiple of font size used for leading. */
  lineHeight: number;
  pageNumbers: boolean;
  tableOfContents: boolean;
  justify: boolean;
  title: string;
  author: string;
  /**
   * Document language: `auto` detects it from the text. Drives hyphenation,
   * line breaking, quote marks, text direction, Han glyph forms and the table
   * of contents title. See `SUPPORTED_LANGUAGES` for the values.
   */
  lang: LangSetting;
  /** Table of contents title; empty means the language's usual word. */
  tocTitle: string;
  /** Page template (src/layout/templates.ts). YAML front matter can override this and most options. */
  template: TemplateId;
  /** A title page from the title, subtitle, author and date; it has no header or footer. */
  cover: boolean;
  /** Start every level-1 heading on a new page. */
  h1NewPage: boolean;
  /**
   * Running header and footer. Tokens: {title} {page} {pages} {date} {author};
   * `|` splits left | centre | right. Empty means the template's own ("{page} /
   * {pages}" for the footer when page numbers are on); `none` means nothing.
   */
  header: string;
  footer: string;
}

